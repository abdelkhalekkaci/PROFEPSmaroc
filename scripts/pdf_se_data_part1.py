def make_q(qid, theme, ref, q_ar, opts_ar, correct_letter, exp_ar, q_fr=None):
    """
    Helper that builds a standardized BANK item for qcm-sciences-education-crmef.html.
    Both `question` and `questionAr` are populated so the question displays clearly
    in both French/bilingual and Arabic modes.
    """
    display_q = q_fr if q_fr else q_ar
    options = []
    letters = ["A", "B", "C", "D", "E"]
    for idx, txt_ar in enumerate(opts_ar):
        if idx >= len(letters):
            break
        ltr = letters[idx]
        options.append({
            "id": ltr,
            "text": txt_ar,
            "textAr": txt_ar,
            "correct": (ltr == correct_letter)
        })
    return {
        "id": qid,
        "theme": theme,
        "reference": ref,
        "question": display_q,
        "questionAr": q_ar,
        "options": options,
        "explanation": exp_ar
    }


